"""Install and read back the seed against the pinned OpenPLC v3 schema."""
import json
import pathlib
import sqlite3
import time

ROOT = pathlib.Path("/root/OpenPLC_v3/webserver")
SEED = pathlib.Path("/opt/openplc-eu")
PROGRAM = "tap-control.st"
DEVICE = json.loads((SEED / "oltc.json").read_text())
SETTINGS = {
    "Start_run_mode": "true",
    "Slave_polling": "100",
    "Slave_timeout": "1000",
    "Modbus_port": "502",
    "Dnp3_port": "disabled",
    "Enip_port": "disabled",
    "Pstorage_polling": "disabled",
}


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def install():
    # mode=rw prevents a missing database from becoming a new empty database.
    with sqlite3.connect("file:" + str(ROOT / "openplc.db") + "?mode=rw", uri=True) as db:
        db.execute("DELETE FROM Programs")
        db.execute(
            "INSERT INTO Programs (Name,Description,File,Date_upload) VALUES (?,?,?,?)",
            ("EU tap control", "Seeded OLTC controller", PROGRAM, int(time.time())),
        )
        db.execute("DELETE FROM Slave_dev")
        columns = list(DEVICE)
        db.execute(
            "INSERT INTO Slave_dev (" + ",".join(columns) + ") VALUES ("
            + ",".join("?" for _ in columns) + ")",
            [DEVICE[key] for key in columns],
        )
        for key, value in SETTINGS.items():
            db.execute("INSERT OR REPLACE INTO Settings (Key,Value) VALUES (?,?)", (key, value))

    # Reopen after commit: verify persisted values, not merely successful SQL.
    with sqlite3.connect("file:" + str(ROOT / "openplc.db") + "?mode=ro", uri=True) as db:
        require(db.execute("SELECT File FROM Programs").fetchall() == [(PROGRAM,)],
                "program verification failed")
        require(db.execute("SELECT " + ",".join(columns) + " FROM Slave_dev").fetchall() == [
            tuple(DEVICE[key] for key in columns)
        ], "slave verification failed")
        actual = dict(db.execute("SELECT Key,Value FROM Settings"))
        require(all(actual[key] == value for key, value in SETTINGS.items()),
                "settings verification failed")
    require((ROOT / "active_program").read_text().strip() == PROGRAM,
            "active program verification failed")

    # Same names consumed by core/modbus_master.cpp and generated by webserver.py.
    mapping = {
        "name": "dev_name", "slave_id": "slave_id", "address": "ip_address",
        "IP_Port": "ip_port", "RTU_Baud_Rate": "baud_rate", "RTU_Parity": "parity",
        "RTU_Data_Bits": "data_bits", "RTU_Stop_Bits": "stop_bits",
        "Discrete_Inputs_Start": "di_start", "Discrete_Inputs_Size": "di_size",
        "Coils_Start": "coil_start", "Coils_Size": "coil_size",
        "Input_Registers_Start": "ir_start", "Input_Registers_Size": "ir_size",
        "Holding_Registers_Read_Start": "hr_read_start",
        "Holding_Registers_Read_Size": "hr_read_size",
        "Holding_Registers_Start": "hr_write_start",
        "Holding_Registers_Size": "hr_write_size",
    }
    config = 'Num_Devices = "1"\nPolling_Period = "100"\nTimeout = "1000"\n'
    config += 'device0.protocol = "TCP"\n'
    config += "".join('device0.{} = "{}"\n'.format(key, DEVICE[value])
                      for key, value in mapping.items())
    (ROOT / "mbconfig.cfg").write_text(config)
    require((ROOT / "mbconfig.cfg").read_text() == config, "master configuration verification failed")


if __name__ == "__main__":
    install()
