import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { getFieldState } from "./operator-api";
import initialProcess from "./fixtures/process-initial.json";

const root = resolve(__dirname, "../..");
const backendFixtures = readFileSync(resolve(root, "backend/internal/server/field_test.go"), "utf8");
function fixture(name: string): unknown {
  const match = backendFixtures.match(new RegExp("const " + name + " = `([^`]+)`"));
  if (!match) throw new Error(`Missing backend fixture ${name}`);
  return JSON.parse(match[1]);
}
const manifest = JSON.parse(readFileSync(resolve(root, "lab-definitions/packages/eu-iec104-substation/manifest.json"), "utf8")) as {
  services: { node: string; roles: string[]; endpoints?: { sim?: string } }[];
};

// Match simServer/TestFieldState: each non-clock upstream returns the same
// unmodified device body. handleFieldState keys those bodies by manifest node.
const backendField = {
  devices: Object.fromEntries(manifest.services.filter((s) => s.endpoints?.sim && !s.roles.includes("time-source"))
    .map((s) => [s.node, fixture("deviceStateFixture")])),
  clock: fixture("clockStateFixture"),
  process: fixture("electricalFixture"),
};
afterEach(() => vi.unstubAllGlobals());

it("parses the backend field handler's test aggregate without adding process protection", async () => {
  expect(backendField.process).not.toHaveProperty("f2_protection");
  expect(Object.keys(backendField.devices).sort()).toEqual(["breaker-1", "f2-breaker", "oltc-1", "rmu-1", "rmu-2"]);
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue(new Response(JSON.stringify(backendField))));
  await expect(getFieldState()).resolves.toEqual(backendField);
});

it("parses the real initial electrical handler response before any device truth arrives", async () => {
  // process-initial.json was generated by create_eu_app(profile). The profile is
  // the shipped EU profile with circuit_file resolved to this checkout's feeder.
  // Calling the /api/electrical endpoint without lifespan/startup runs no solve
  // and contacts no devices. The body is saved verbatim (only JSON indentation).
  const answer = { ...backendField, process: initialProcess };
  expect(initialProcess).toMatchObject({ solve_seq: 0, tap: null, f2_tripped: null, truth_stale: true });
  expect(Object.keys(initialProcess.devices)).toHaveLength(5);
  expect(initialProcess).not.toHaveProperty("f2_protection");
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue(new Response(JSON.stringify(answer))));
  const field = await getFieldState();
  expect(field).toEqual(answer);
  expect(field.process.f2_tripped).toBeNull();
  expect(field.process.tap).toBeNull();
});
